-- 3) 기존 "테스트 상품" 정리
--
-- 삭제하지 않고 새 트리로 옮긴다. product id=1 은 order.api 의 주문 항목과
-- wishlist_items 가 참조할 수 있는데, 그건 이 DB 밖이라 FK 로 보호되지 않는다.
-- 지우면 기존 주문 내역이 조용히 깨진다. 옮기기만 하면 그런 일이 없다.
-- ---------------------------------------------------------
UPDATE products
   SET category_id = 9101, is_demo = TRUE
 WHERE id = 1 AND name = '테스트 상품';

-- 이제 아무 상품도 참조하지 않는 옛 카테고리(의류/상의/하의)를 정리한다.
-- 이름이 아니라 "상품이 하나도 안 달린 비데모 카테고리"로 지워서, 혹시 다른 세션이
-- 그 사이 상품을 붙였다면 살아남게 한다.
DELETE FROM categories c
 WHERE c.is_demo = FALSE
   AND NOT EXISTS (SELECT 1 FROM products p WHERE p.category_id = c.id)
   AND NOT EXISTS (SELECT 1 FROM categories x WHERE x.parent_id = c.id AND x.is_demo = FALSE);
DELETE FROM categories c
 WHERE c.is_demo = FALSE
   AND NOT EXISTS (SELECT 1 FROM products p WHERE p.category_id = c.id)
   AND NOT EXISTS (SELECT 1 FROM categories x WHERE x.parent_id = c.id);

