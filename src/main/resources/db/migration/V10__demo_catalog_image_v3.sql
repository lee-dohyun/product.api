-- =========================================================
-- 데모 카탈로그 상품 이미지 v3 전환 (product.api#41)
--
-- V9(product.api#36)에서 상품에 심볼 마크를 넣었는데, 상품 카드처럼 폭이 좁은
-- 자리에서는 마크 하나만으로는 화면이 밋밋했다. 그래서 정중앙에 카테고리별 컬러
-- 이모지를 크게 넣고, 브랜드 로고("Positively Selected", 원색 그대로)는 배경색
-- 위에 직접·우하단으로 옮겼다. 이모지는 중분류(26개) 단위로 다르게 골라 128개
-- 상품이 8종 대분류 색상 블록보다 다양하게 보이게 했다.
--
-- **배너는 이번에 안 건드린다.** 배너는 V9에서 이미 워드마크(v2)를 쓰고 있고
-- 그 배치가 그대로 유효해서 재작업 대상이 아니다 - 이 마이그레이션은 상품
-- 이미지(product_images)만 옮긴다.
--
-- 왜 같은 키로 덮어쓰지 않고 마이그레이션까지 필요한가 (V9와 동일한 이유):
--   CDN 응답이 Cache-Control: max-age=31536000(1년)이다. 같은 키로 덮어쓰면
--   next/image 디스크 캐시와 방문자 브라우저가 1년 동안 옛 이미지를 붙든다.
--   그래서 키에 버전을 넣고(products/v3/...) 여기서 URL 을 옮긴다.
--
-- 이미지 실체는 이미 CDN 에 올라가 있다(상품 384개). 이 마이그레이션은 참조만 바꾼다.
-- =========================================================

-- V8 이 넣은 데모 상품(id 9000번대)만 대상. 옛 "테스트 상품"(id=1)은 V9 때와 같은
-- 이유로 제외한다 - 생성기 자산이 아니라서 v3 가 존재하지 않는다.
UPDATE product_images
   SET image_url = replace(image_url, '/cdn/products/v2/', '/cdn/products/v3/')
 WHERE product_id >= 9001
   AND image_url LIKE '%/cdn/products/v2/%';
